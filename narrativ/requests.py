"""User scan requests: data/scan_requests.txt + open GitHub issues labelled 'scan' (title 'scan: SYMBOL').
After Claude has worked on a requested stock, close_done() comments on and closes its issue."""
import os
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path

import requests

FILE = Path("data/scan_requests.txt")
API = "https://api.github.com"
SIGNATURE = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
IST = timezone(timedelta(hours=5, minutes=30))


def _norm(tok: str, known: set[str]) -> str | None:
    tok = tok.strip().upper()
    if not tok:
        return None
    if tok.endswith((".NS", ".BO")):
        # a listing we do not score under that suffix but do under the other (BONDADA.BO asked, BONDADA.NS scored: the review
        # run of 28 Nov 2026 found no dossier for the .BO symbol and was blocked)
        alt = tok[:-3] + (".NS" if tok.endswith(".BO") else ".BO")
        return alt if known and tok not in known and alt in known else tok
    for suf in (".NS", ".BO"):
        if tok + suf in known:
            return tok + suf
    return tok + ".NS"


def _ist_date(ts: str | None) -> str | None:
    """GitHub's UTC timestamp -> the IST calendar date (the dates in theses.json are IST)."""
    try:
        return datetime.fromisoformat(str(ts).replace("Z", "+00:00")).astimezone(IST).date().isoformat()
    except (TypeError, ValueError):
        return None


def load(known: set[str]) -> list[dict]:
    out = []
    if FILE.exists():
        for line in FILE.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                s = _norm(line.split()[0], known)
                if s:
                    out.append({"symbol": s, "via": "file"})
    repo, tok = (os.environ.get("NARRATIV_REPO") or os.environ.get("GITHUB_REPOSITORY")), os.environ.get("GITHUB_TOKEN")
    if repo and tok:
        try:
            r = requests.get(f"https://api.github.com/repos/{repo}/issues",
                             params={"labels": "scan", "state": "open", "per_page": 100},
                             headers={"Authorization": f"Bearer {tok}", "Accept": "application/vnd.github+json"}, timeout=30)
            for it in r.json() if r.ok else []:
                m = re.search(r"scan:\s*([A-Za-z0-9&\-.]+)", it.get("title", ""), re.I)
                if m and (s := _norm(m.group(1), known)):
                    out.append({"symbol": s, "via": f"issue #{it['number']}", "issue": it["number"], "date": _ist_date(it.get("created_at"))})
        except Exception as e:  # noqa: BLE001
            print(f"[requests] issues read failed: {e}")
    seen, res = set(), []
    for x in out:
        if x["symbol"] not in seen:
            seen.add(x["symbol"])
            res.append(x)
    return res


def reviewed_on(th: dict | None) -> str | None:
    """Latest date Claude worked on the stock: thesis update, full review (audit) or deep scan."""
    th = th or {}
    ds = [str(d)[:10] for d in (th.get("updated"), (th.get("audit") or {}).get("date"), (th.get("scan") or {}).get("date")) if d]
    return max(ds) if ds else None


def done(requests_: list[dict], theses: dict) -> list[dict]:
    """Issue requests Claude has since worked on: the stock's updated / review / scan date is on or after the request date."""
    out = []
    for r in requests_:
        d, th = r.get("date"), theses.get(r["symbol"])
        got = reviewed_on(th)
        if r.get("issue") and d and got and got >= d:
            out.append({**r, "reviewed": got, "verdict": ((th or {}).get("audit") or {}).get("verdict")})
    return out


def comment_text(r: dict) -> str:
    v = f" Verdict: {r['verdict']}." if r.get("verdict") else ""
    return (f"Claude reviewed {r['symbol']} on {r['reviewed']} (request of {r['date']}).{v} The research and any full review are in the "
            "app under this stock (Claude's research). Closing this scan request." + SIGNATURE)


def close_done(requests_: list[dict], theses: dict, repo: str | None = None, tok: str | None = None, http=requests) -> list[int]:
    """Comment on and close the GitHub issue of every request Claude has worked on since it was made. Returns the closed issue
    numbers. Needs a token with `issues: write` (daily.yml grants it since 20 Nov 2026; without it the comment fails with 403,
    which is printed and the issue stays open)."""
    repo, tok = repo or (os.environ.get("NARRATIV_REPO") or os.environ.get("GITHUB_REPOSITORY")), tok or os.environ.get("GITHUB_TOKEN")
    if not (repo and tok):
        return []
    hdr = {"Authorization": f"Bearer {tok}", "Accept": "application/vnd.github+json"}
    closed = []
    for r in done(requests_, theses):
        url = f"{API}/repos/{repo}/issues/{r['issue']}"
        try:
            c = http.post(f"{url}/comments", json={"body": comment_text(r)}, headers=hdr, timeout=30)
            if not c.ok:
                print(f"[requests] comment on #{r['issue']} failed: HTTP {c.status_code} (the token needs issues: write)")
                continue
            p = http.patch(url, json={"state": "closed", "state_reason": "completed"}, headers=hdr, timeout=30)
            if p.ok:
                closed.append(r["issue"])
            else:
                print(f"[requests] close #{r['issue']} failed: HTTP {p.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"[requests] close #{r['issue']} failed: {e}")
    return closed
