"""Stocks a research run could not finish (owner, 28 Nov 2026: "what happens to blocked stocks?").

A run that cannot finish an item leaves the stock as it was and lists it in its run log line (docs/data/research_runs.jsonl,
"blocked": [{"symbol", "why"}]). A stock blocked STUCK_AFTER or more times in the last DAYS days, with no research saved since
the last block, is stuck:
  - the live feed (narrativ/next.py) stops serving it, so it does not cost every run a few minutes;
  - sync_issues() (run every 30 minutes by narrativ/requeue.py) opens one GitHub issue per stuck stock, "blocked: SYMBOL",
    labelled "blocked", with each reason and date, and closes it once research on the stock is saved again;
  - closing the issue yourself clears the stop: the feed serves the stock again (docs/data/blocked.json "cleared").
"""
import json
import os
from datetime import date, timedelta
from pathlib import Path

RUNS = Path("docs/data/research_runs.jsonl")
STATE = Path("docs/data/blocked.json")
DAYS = 3
STUCK_AFTER = 2
API = "https://api.github.com"
SIGNATURE = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def _sym(s: str) -> str:
    s = str(s or "").strip().upper()
    return s if not s or s.endswith((".NS", ".BO")) else s + ".NS"


def recent(lines: list[str], today: date, days: int = DAYS) -> dict[str, list[dict]]:
    """{symbol: [{"date", "why", "task"}]} from run log lines of the last `days` days, oldest first."""
    cut = str(today - timedelta(days=days - 1))
    out: dict[str, list[dict]] = {}
    for ln in lines:
        try:
            r = json.loads(ln)
        except ValueError:
            continue
        d = str(r.get("start") or "")[:10]
        if d < cut:
            continue
        for b in r.get("blocked") or []:
            if isinstance(b, dict) and b.get("symbol"):
                out.setdefault(_sym(b["symbol"]), []).append({"date": d, "why": str(b.get("why") or "")[:300], "task": r.get("task")})
    return out


def stuck(blocks: dict[str, list[dict]], theses: dict, cleared: dict | None = None) -> dict[str, list[dict]]:
    """Stocks blocked STUCK_AFTER+ times with no research saved since the last block and not cleared since it."""
    out = {}
    for s, bs in blocks.items():
        last = max(b["date"] for b in bs)
        upd = str((theses.get(s) or {}).get("updated") or "")[:10]
        if len(bs) >= STUCK_AFTER and upd < last and str((cleared or {}).get(s) or "") < last:
            out[s] = bs
    return out


def load_state() -> dict:
    try:
        return json.loads(STATE.read_text()) if STATE.exists() else {}
    except ValueError:
        return {}


def live(theses: dict, today: date) -> set[str]:
    """Stuck stocks now (for the feed between syncs): from the run log and the cleared list, plus the last sync's list
    (it holds stocks with an open issue), less any researched since."""
    lines = RUNS.read_text().splitlines() if RUNS.exists() else []
    st = load_state()
    out = set(stuck(recent(lines, today), theses, st.get("cleared")))
    for s in st.get("stuck") or {}:
        if str((theses.get(s) or {}).get("updated") or "")[:10] < str(st.get("date") or ""):
            out.add(s)
    return out


def body(sym: str, bs: list[dict]) -> str:
    rows = "\n".join(f"- {b['date']} ({b.get('task') or 'run'}): {b['why']}" for b in bs)
    return (f"Research runs could not finish {sym} {len(bs)} times in the last {DAYS} days, so the research feed has stopped serving "
            f"it.\n\n{rows}\n\nClose this issue to let the runs try again (for example after fixing the cause). It closes by itself "
            "once research on the stock is saved." + SIGNATURE)


def sync_issues(theses: dict, today: date, repo: str | None = None, tok: str | None = None, http=None) -> dict:
    """Open / update / close the "blocked: SYMBOL" issues and write docs/data/blocked.json. Returns the state."""
    import requests
    http = http or requests
    repo, tok = repo or os.environ.get("NARRATIV_REPO") or os.environ.get("GITHUB_REPOSITORY"), tok or os.environ.get("GITHUB_TOKEN")
    state = load_state()
    cleared = dict(state.get("cleared") or {})
    lines = RUNS.read_text().splitlines() if RUNS.exists() else []
    blocks = recent(lines, today)
    issues: list[dict] = []
    hdr = {"Authorization": f"Bearer {tok}", "Accept": "application/vnd.github+json"} if tok else {}
    if repo and tok:
        try:
            r = http.get(f"{API}/repos/{repo}/issues", params={"labels": "blocked", "state": "all", "per_page": 100}, headers=hdr, timeout=30)
            issues = r.json() if r.ok else []
        except Exception as e:  # noqa: BLE001
            print(f"[blocked] issues read failed: {e}")
    by_sym: dict[str, list[dict]] = {}
    for it in issues:
        t = str(it.get("title") or "")
        if t.lower().startswith("blocked:"):
            by_sym.setdefault(_sym(t.split(":", 1)[1]), []).append(it)
    for s, its in by_sym.items():  # closed after the last block (by the owner, or on saved research): cleared
        bs = blocks.get(s)
        for it in its:
            if it.get("state") == "closed" and it.get("closed_at") and bs and str(it["closed_at"])[:10] >= max(b["date"] for b in bs):
                cleared[s] = max(str(cleared.get(s) or ""), str(it["closed_at"])[:10])
    now = stuck(blocks, theses, cleared)
    for s, its in by_sym.items():  # an open issue keeps its stock stopped until research is saved or the issue is closed
        it = next((x for x in its if x.get("state") == "open"), None)
        upd = str((theses.get(s) or {}).get("updated") or "")[:10]
        if it and s not in now and not (upd and upd >= str(it.get("created_at") or "")[:10]):
            now[s] = blocks.get(s) or []
    if repo and tok:
        for s, bs in now.items():
            open_ = next((it for it in by_sym.get(s, []) if it.get("state") == "open"), None)
            try:
                if open_ is None:
                    http.post(f"{API}/repos/{repo}/issues", json={"title": f"blocked: {s}", "body": body(s, bs), "labels": ["blocked"]},
                              headers=hdr, timeout=30)
                elif open_.get("body") != body(s, bs):
                    http.patch(f"{API}/repos/{repo}/issues/{open_['number']}", json={"body": body(s, bs)}, headers=hdr, timeout=30)
            except Exception as e:  # noqa: BLE001
                print(f"[blocked] issue for {s} failed: {e}")
        for s, its in by_sym.items():  # research saved since: the stock is unblocked
            upd = str((theses.get(s) or {}).get("updated") or "")[:10]
            for it in its:
                if it.get("state") == "open" and s not in now and upd and upd >= str(it.get("created_at") or "")[:10]:
                    try:
                        http.post(f"{API}/repos/{repo}/issues/{it['number']}/comments",
                                  json={"body": f"Research on {s} was saved on {upd}: unblocked." + SIGNATURE}, headers=hdr, timeout=30)
                        http.patch(f"{API}/repos/{repo}/issues/{it['number']}", json={"state": "closed", "state_reason": "completed"},
                                   headers=hdr, timeout=30)
                    except Exception as e:  # noqa: BLE001
                        print(f"[blocked] close for {s} failed: {e}")
    keep = str(today - timedelta(days=30))
    out = {"date": str(today), "stuck": now, "cleared": {s: d for s, d in cleared.items() if d >= keep}}
    STATE.write_text(json.dumps(out, indent=1, ensure_ascii=False))
    return out
